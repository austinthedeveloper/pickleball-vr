#!/usr/bin/env python3
"""Builds game/data/opponents.json from the port kit's ladder
(../pickleball-port-kit/game/data/opponents.json): the eight teams, their
lines and shirt colours, with each player's SNES AI knobs re-cut into the
VR sim's CpuStyle (metres, ticks, percents). Rerun after the port kit's
ladder changes:  python3 game/tools/import_opponents.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "../../../pickleball-port-kit/game/data/opponents.json")
OUT = os.path.join(HERE, "../data/opponents.json")
AIMS = {"away": 0, "body": 1, "mix": 2}


def colour(rgb5):
    return [round(c / 31, 3) for c in rgb5]


def style(s, rung):
    return {
        "speed": 26000 + (s.get("speed", 16) - 13) * 1500,        # um/tick
        "reaction": 26 - rung * 2,                                 # ticks
        "error": 520000 - rung * 45000,                            # um
        "net_rush": {0: 20, 44: 60}.get(s.get("net", 0), 80),      # percent
        "dink": 40 + s["dink_period"] * 6 if s.get("dink_period", 0) else 25,
        "lob": min(40, s.get("lob_distance", 0) // 2),
        "drive_pace": 115000 + rung * 4000,                        # um/tick
        "serve_pace": 90000 + rung * 2500,
        "aim": AIMS.get(s.get("aim", "away"), 0),
        "miss": 12 - rung,                                         # percent at NORMAL
    }


def main():
    src = json.load(open(SRC))
    teams = []
    for rung, t in enumerate(src["opponents"]):
        teams.append({
            "team": t["team"],
            "intro": t["intro"],
            "taunt": t["taunt"],
            "concede": t["concede"],
            "quips": t["quips"][:8],
            "players": [{
                "name": p["name"],
                "shirt": colour(p["shirt"][1]),
                "shorts": colour(p["shorts"][0]),
                "style": style(p["style"], rung),
            } for p in t["players"]],
        })
    json.dump({"comment": "Generated by game/tools/import_opponents.py from the port kit's ladder.",
               "opponents": teams}, open(OUT, "w"), indent=1)
    print("wrote", OUT, len(teams), "teams")


main()
